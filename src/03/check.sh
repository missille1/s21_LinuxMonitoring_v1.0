#!/bin/bash

param () {
    [ "$#" -ne 4 ] && { echo "Нужно 4 параметра.
    1 — white, 2 — red, 3 — green, 4 — blue, 5 – purple, 6 — black"; exit 1; }

    for i in 1 2 3 4; do
        v=$(eval "echo \${$i}")
        [[ "$v" =~ ^[1-6]$ ]] || { echo "Параметр $i должен быть числом 1 - 6"; exit 1; }
    done

    # фон и шрифт != совпадать
    [ "$1" -eq "$2" ] && { echo "Ошибка - цвет совпадает с фоном"; exit 1; }
    [ "$3" -eq "$4" ] && { echo "Ошибка - цвет совпадает с фоном"; exit 1; }
}